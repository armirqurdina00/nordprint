const DICTS: Record<AdminLang, AdminDict> = { sv, en };

export function adminT(lang: AdminLang): AdminDict {
  return DICTS[lang];
}

export function isAdminLang(v: unknown): v is AdminLang {
  return v === "sv" || v === "en";
}

/** Translates an UploadError-like object ({ kind, detail, mb }) into a message. */
export function uploadErrorMessage(t: AdminDict, e: { kind: string; detail: string; mb?: number }) {
  switch (e.kind) {
    case "type":
      return t.errors.fileType(e.detail);
    case "size":
      return t.errors.fileSize(e.detail, e.mb ?? 0);
    case "storage":
      return t.errors.noBlob;
    default:
      return t.errors.uploadFailed(e.detail);
  }
}
